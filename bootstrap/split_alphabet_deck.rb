#!/usr/bin/env ruby
# frozen_string_literal: true

# Split the single "🕉️ Sanskrit Alphabet" deck into numbered subdecks, in your
# running Anki, via the AnkiConnect add-on (code 2055492159). Moving a card
# between decks keeps its review history: the history belongs to the card.
#
#   ruby split_alphabet_deck.rb          # dry run: shows what would move, changes nothing
#   ruby split_alphabet_deck.rb --apply  # actually move the cards
#
# Anki must be open with AnkiConnect installed. Make a backup first
# (File > Create Backup).
#
# How cards are classified: the deck files' Key column is the note GUID, not a
# field, so Anki can't search it. Instead every card's Front (its big glyph,
# HTML stripped) is looked up in the repo's own deck files, where all 553 fronts
# are unique. The letters file is split into vowels and consonants by its Key.
#
# Retired cards: re-importing never deletes, so older imports can leave cards the
# repo no longer generates (combinations pruned as unattested, and the old
# independent-vowel + mark cards आः इं ओं that were re-carded in the anusvāra
# deck under new keys, leaving a stale duplicate). Those go to
# "🕉️ Sanskrit Alphabet::Retired" and are SUSPENDED, not deleted, so nothing is
# lost; delete that subdeck in Anki whenever you like. A stale duplicate is told
# from its replacement by its back: of several cards sharing a front, the ones
# whose back differs from the current deck file are retired.

require "json"
require "net/http"

REPO   = ENV.fetch("ANKI_SANSKRIT_REPO", "/Users/noj/Development/anki-sanskrit")
PARENT = "🕉️ Sanskrit Alphabet"
# Only cards sitting directly in the parent, so a re-run never touches cards
# that have already been moved into a subdeck.
IN_PARENT = %("deck:#{PARENT}" -"deck:#{PARENT}::*")

VOWEL_KEYS = %w[a ā i ī u ū ṛ ṝ ḷ e ai o au aṁ aḥ].freeze
FILES = {
  "sanskrit_anki.txt"              => nil, # vowels / consonants, decided by key
  "sanskrit_combinations_anki.txt" => "3. Combinations",
  "sanskrit_conjuncts_anki.txt"    => "4. Conjuncts",
  "sanskrit_anusvara_anki.txt"     => "5. Anusvāra"
}.freeze

def glyph(html) = html.to_s.gsub(/<[^>]+>/, "").gsub("&nbsp;", " ").strip

RETIRED = "Retired"

# glyph(front) -> [subdeck name, glyph(back)], from the repo's deck files.
def subdeck_by_glyph
  FILES.each_with_object({}) do |(file, subdeck), map|
    path = File.join(REPO, file)
    abort "Missing #{path}; set ANKI_SANSKRIT_REPO to the repo checkout." unless File.exist?(path)
    File.readlines(path, chomp: true).each do |line|
      next if line.start_with?("#")

      key, front, back = line.split("\t")
      map[glyph(front)] = [subdeck || (VOWEL_KEYS.include?(key) ? "1. Vowels" : "2. Consonants"), glyph(back)]
    end
  end
end

def anki(action, **params)
  body = { action: action, version: 6, params: params }.to_json
  res = JSON.parse(Net::HTTP.post(URI("http://127.0.0.1:8765"), body, "Content-Type" => "application/json").body)
  raise "AnkiConnect #{action}: #{res['error']}" if res["error"]

  res["result"]
rescue Errno::ECONNREFUSED
  abort "Can't reach AnkiConnect on port 8765. Is Anki open with the AnkiConnect add-on installed?"
end

apply = ARGV.include?("--apply")
lookup = subdeck_by_glyph
cards = anki("findCards", query: IN_PARENT)
abort "No cards directly in #{PARENT}; nothing to do." if cards.empty?

infos = anki("cardsInfo", cards: cards).map do |info|
  [info["cardId"], glyph(info.dig("fields", "Front", "value")), glyph(info.dig("fields", "Back", "value"))]
end
shared_front = infos.map { |_, front, _| front }.tally

plan = Hash.new { |h, k| h[k] = [] }
infos.each do |id, front, back|
  subdeck, current_back = lookup[front]
  if subdeck.nil?
    plan[RETIRED] << id                                   # no longer generated at all
  elsif shared_front[front] > 1 && back != current_back
    plan[RETIRED] << id                                   # stale duplicate of a re-carded card
  else
    plan[subdeck] << id
  end
end

puts "#{cards.size} cards directly in #{PARENT}. #{apply ? 'Moving:' : 'Dry run (pass --apply to move):'}"
plan.sort.each do |subdeck, ids|
  note = subdeck == RETIRED ? "  (no longer generated by the repo; will be suspended)" : ""
  puts format("  %4d cards -> %s::%s%s", ids.size, PARENT, subdeck, note)
end

exit unless apply

plan.each { |subdeck, ids| anki("changeDeck", cards: ids, deck: "#{PARENT}::#{subdeck}") }
anki("suspend", cards: plan[RETIRED]) unless plan[RETIRED].empty?
puts "\nDone. #{anki('findCards', query: IN_PARENT).size} cards left directly in #{PARENT}."
